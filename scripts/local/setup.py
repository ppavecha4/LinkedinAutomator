#!/usr/bin/env python3
"""Write .env.local for running the whole system on this computer.

    python scripts/local/setup.py
    python scripts/local/setup.py --admin-email you@example.com
    python scripts/local/setup.py --anthropic-key sk-ant-...      # optional, see below

It creates fresh random secrets (database passwords, session secret, the key
that encrypts customers' connected-account secrets, ...) and NEVER overwrites
an existing .env.local (that would change CREDENTIALS_KEY and make everything
already saved unreadable): to start over, delete the file AND run
`docker compose -f docker-compose.local.yml --env-file .env.local down -v`.

Your existing .env (the operator / VPS settings) is not read or changed.

--admin-email   makes that address a platform administrator (sees Platform >
                Companies and System health). It must verify its email: the
                verification link arrives in Mailpit, http://localhost:8025.
--anthropic-key the platform's own Anthropic key. Only the onboarding helpers
                (read my website, AI summary) use it, up to 15 calls per company;
                everything else uses the key each company connects itself.
"""
from __future__ import annotations

import argparse
import base64
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / ".env.local"


def token(n: int = 24) -> str:
    return secrets.token_urlsafe(n)


def render(admin_email: str, anthropic_key: str) -> str:
    unsub = token()
    return f"""# Generated by scripts/local/setup.py: local use only. Never commit; never reuse in production.
# Losing CREDENTIALS_KEY makes every connected-account secret saved so far unreadable.

# ── database ──
POSTGRES_PASSWORD={token()}
SALES_APP_DB_PASSWORD={token()}

# ── API ──
NODE_ENV=development
LOG_LEVEL=info
AUTH_MODE=local
AUTH_JWT_SECRET={token(32)}
SIGNUP_ENABLED=true
CREDENTIALS_KEY={base64.b64encode(secrets.token_bytes(32)).decode()}
# Ports differ from the older dev stack (3000 / 5173) so both can run at once. Change them
# here (and DASHBOARD_URL / CORS_ORIGINS / UNSUBSCRIBE_BASE_URL to match) if they clash.
LOCAL_API_PORT=3100
LOCAL_DASHBOARD_PORT=5180
LOCAL_MAIL_PORT=8025
LOCAL_PG_PORT=5433
LOCAL_VOICE_PORT=8090
DASHBOARD_URL=http://localhost:5180
CORS_ORIGINS=http://localhost:5180

# Platform emails (invites, verification, password reset, alerts) go to Mailpit: http://localhost:8025
PLATFORM_SMTP_HOST=mailpit
PLATFORM_SMTP_PORT=1025
PLATFORM_SMTP_PLAIN=true
PLATFORM_MAIL_FROM=AmiReach <no-reply@localhost>
REQUIRE_VERIFIED_EMAIL=true
PLATFORM_ADMIN_EMAILS={admin_email}

# The platform's own Anthropic key (onboarding helpers only; companies connect their own).
ANTHROPIC_API_KEY={anthropic_key}

# Unsubscribe links: the orchestrator signs, the API checks: same secret.
UNSUBSCRIBE_SECRET={unsub}
UNSUBSCRIBE_HMAC_SECRET={unsub}
UNSUBSCRIBE_BASE_URL=http://localhost:3100

# ── monitoring: only the jobs that exist locally ──
OPS_EXPECTED_HEARTBEATS=auto_sends:20,poll_replies:30,proc_inbound:30
OPS_GRACE_MINUTES=5

# ── AI phone calls (docs/run-locally.md, "Voice") ──
VOICE_PUBLIC_URL=
VOICE_STREAM_SECRET={token()}
VOICE_MAX_CONCURRENT=2
"""


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--admin-email", default="", help="make this address a platform administrator")
    p.add_argument("--anthropic-key", default="", help="the platform's own Anthropic API key (optional)")
    a = p.parse_args()
    if TARGET.exists():
        print(f"{TARGET.name} already exists: left untouched (see --help to start over).")
        return 0
    TARGET.write_text(render(a.admin_email.strip().lower(), a.anthropic_key.strip()), encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.name}")
    if not a.admin_email:
        print("  tip: re-run with --admin-email you@example.com (after deleting the file) to get the Platform pages")
    if not a.anthropic_key:
        print("  note: no platform Anthropic key set: the onboarding helpers (read my website, AI summary) will say they are unavailable")
    return 0


if __name__ == "__main__":
    sys.exit(main())
